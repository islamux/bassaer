# 2. REGEX-BASED REPLACEMENTS (for patterns with variation)
# ============================================================================
REGEX_REPLACEMENTS = [
    # Fix double spaces
    (r'  +', ' '),
    
    # Fix ﷺ spacing
    (r'\s*ﷺ\s*', ' ﷺ '),
    
    # Fix "ي " at start of words (common OCR artifact meaning في)
    # Be careful - only fix where it clearly should be في
]

def apply_fixes(text):
    """Apply all fixes to the given text."""
    # 1. Apply direct replacements (longer matches first to avoid conflicts)
    sorted_replacements = sorted(DIRECT_REPLACEMENTS.items(), key=lambda x: -len(x[0]))
    for old, new in sorted_replacements:
        text = text.replace(old, new)
    
    # 2. Apply regex replacements
    for pattern, replacement in REGEX_REPLACEMENTS:
        text = re.sub(pattern, replacement, text)
    
    # 3. Normalize multiple spaces
    text = re.sub(r' {2,}', ' ', text)
    
    return text


def process_file(filepath):
    """Process a single markdown file."""
    print(f"Processing: {filepath}")
    with open(filepath, 'r', encoding='utf-8') as f:
        original = f.read()
    
    fixed = apply_fixes(original)
    
    if original != fixed:
        # Count changes
        changes = 0
        for old, new in DIRECT_REPLACEMENTS.items():
            count = original.count(old)
            if count > 0:
                changes += count
        
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(fixed)
        print(f"  ✓ Fixed ~{changes} occurrences in {os.path.basename(filepath)}")
    else:
        print(f"  - No changes needed in {os.path.basename(filepath)}")



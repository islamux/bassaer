# REGEX-BASED REPLACEMENTS
# ============================================================================
REGEX_REPLACEMENTS = [
    # Fix الإ  → إلا (with trailing double space pattern)
    (r'الإ\s{2,}', 'إلا '),
    (r'الإ (?=[^\u0600-\u065Fا-ي])', 'إلا '),
    
    # Fix punctuation spacing (remove space before punctuation)
    (r' ،', '،'),
    (r' ؛', '؛'),
    (r' \!', '!'),
    
    # Fix double spaces
    (r'  +', ' '),
    
    # Fix ﷺ spacing
    (r'\s*ﷺ\s*', ' ﷺ '),
]

# ============================================================================
# COUNTING AND LOGGING
# ============================================================================
corrections_log = defaultdict(int)

def apply_fixes(text, filename=""):
    """Apply all fixes to the given text."""
    original_text = text
    
    # 1. Apply direct replacements (longer matches first to avoid conflicts)
    sorted_replacements = sorted(DIRECT_REPLACEMENTS.items(), key=lambda x: -len(x[0]))
    for old, new in sorted_replacements:
        if old != new and old in text:
            count = text.count(old)
            corrections_log[f"{old} → {new}"] += count
            text = text.replace(old, new)
    
    # 2. Apply regex replacements
    for pattern, replacement in REGEX_REPLACEMENTS:
        text = re.sub(pattern, replacement, text)
    
    # 3. Final cleanup: normalize multiple spaces
    text = re.sub(r' {2,}', ' ', text)
    
    return text


def process_file(filepath, dry_run=False):
    """Process a single markdown file."""
    filename = os.path.basename(filepath)
    print(f"Processing: {filename}")
    
    with open(filepath, 'r', encoding='utf-8') as f:
        original = f.read()
    
    fixed = apply_fixes(original, filename)
    
    if original != fixed:
        # Count total changes
        total_changes = sum(1 for a, b in zip(original, fixed) if a != b) + abs(len(original) - len(fixed))
        
        if not dry_run:
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(fixed)
            print(f"  ✓ Applied corrections to {filename}")
        else:
            print(f"  [DRY RUN] Would apply corrections to {filename}")
        
        return True
    else:
        print(f"  - No changes needed in {filename}")
        return False


